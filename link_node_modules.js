import fs from 'fs';
import path from 'path';

function main() {
  if (!fs.existsSync('bun.lock')) {
    console.log('bun.lock not found!');
    return;
  }

  const lockText = fs.readFileSync('bun.lock', 'utf8');
  // Use Function to safely evaluate JSONC/JSON5 style JS object
  const lock = new Function(`return ${lockText}`)();

  // 1. Recreate root node_modules directory
  fs.mkdirSync('node_modules', { recursive: true });
  fs.mkdirSync('node_modules/@opencora', { recursive: true });

  // 2. Get list of directories in node_modules/.bun/
  const bunDir = 'node_modules/.bun';
  if (!fs.existsSync(bunDir)) {
    console.log(`${bunDir} does not exist!`);
    return;
  }
  const bunSubdirs = fs.readdirSync(bunDir);

  function isTopLevel(key) {
    if (key.startsWith('@')) {
      return (key.match(/\//g) || []).length === 1;
    }
    return !key.includes('/');
  }

  // 3. Link all packages in bun.lock to root node_modules
  const packages = lock.packages || {};
  for (const [pkgKey, pkgVal] of Object.entries(packages)) {
    if (!isTopLevel(pkgKey)) {
      continue;
    }
    const resolvedName = pkgVal[0]; // e.g. "zod@4.1.8" or "@actions/artifact@5.0.1"
    
    // Determine package name and version
    let pkgName, pkgVer;
    if (resolvedName.startsWith('@')) {
      const parts = resolvedName.slice(1).split('@');
      pkgName = '@' + parts[0];
      pkgVer = parts[1];
    } else {
      const parts = resolvedName.split('@');
      pkgName = parts[0];
      pkgVer = parts[1];
    }

    // Prefix to match in node_modules/.bun/
    const bunPrefix = pkgName.replace(/\//g, '+') + '@' + pkgVer;

    // Find matching directory in .bun/
    let matchingSubdir = null;
    for (const subdir of bunSubdirs) {
      if (subdir === bunPrefix || subdir.startsWith(bunPrefix + '+')) {
        matchingSubdir = subdir;
        break;
      }
    }

    if (!matchingSubdir) {
      continue;
    }

    // Target path inside .bun
    const pkgSrcRelative = path.join('.bun', matchingSubdir, 'node_modules', pkgName);
    const pkgSrcAbsolute = path.resolve('node_modules', pkgSrcRelative);

    // Link path in root node_modules
    const pkgDest = path.join('node_modules', pkgName);

    // Create parent dir if scoped
    if (pkgName.startsWith('@')) {
      fs.mkdirSync(path.dirname(pkgDest), { recursive: true });
    }

    // Create symlink (remove existing link/file if any)
    let exists = false;
    try {
      fs.lstatSync(pkgDest);
      exists = true;
    } catch (e) {}

    if (exists) {
      try {
        fs.unlinkSync(pkgDest);
      } catch (e) {
        continue; // Keep existing directory if it's a real folder
      }
    }

    // Link source relative to the destination directory
    const destDir = path.dirname(pkgDest);
    const relLinkSrc = path.relative(destDir, pkgSrcAbsolute);

    fs.symlinkSync(relLinkSrc, pkgDest);
  }

  // 4. Link workspace packages
  const workspaces = lock.workspaces || {};
  for (const [wsPath, wsVal] of Object.entries(workspaces)) {
    if (!wsPath || wsPath === '.') {
      continue;
    }

    let wsName = wsVal.name;
    if (!wsName) {
      const wsPkgJson = path.join(wsPath, 'package.json');
      if (fs.existsSync(wsPkgJson)) {
        wsName = JSON.parse(fs.readFileSync(wsPkgJson, 'utf8')).name;
      }
    }

    if (!wsName) {
      continue;
    }

    const pkgDest = path.join('node_modules', wsName);
    if (wsName.startsWith('@')) {
      fs.mkdirSync(path.dirname(pkgDest), { recursive: true });
    }

    let wsExists = false;
    try {
      fs.lstatSync(pkgDest);
      wsExists = true;
    } catch (e) {}

    if (wsExists) {
      try {
        fs.unlinkSync(pkgDest);
      } catch (e) {
        continue;
      }
    }

    const destDir = path.dirname(pkgDest);
    const wsAbsolute = path.resolve(wsPath);
    const relLinkSrc = path.relative(destDir, wsAbsolute);

    fs.symlinkSync(relLinkSrc, pkgDest);
    console.log(`Linked workspace ${wsName} -> ${wsPath}`);
  }

  console.log('Offline node_modules symlinking completed!');
}

main();
